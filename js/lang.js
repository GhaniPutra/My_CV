function updateLanguage(lang) {
  const dictionary = translations[lang];
  if (!dictionary) return;

  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value === undefined) return;

    if (element.dataset.i18n === 'about_intro') {
      element.innerHTML = value;
    } else {
      element.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const value = dictionary[element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute('aria-label', value);
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute('alt', value);
  });

  document.querySelectorAll('[data-i18n-title]').forEach((element) => {
    const value = dictionary[element.dataset.i18nTitle];
    if (value !== undefined) element.setAttribute('title', value);
  });

  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.textContent = dictionary.toggle_lang;
    toggle.setAttribute('aria-label', dictionary.toggle_lang_label);
  }

  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
  const toggle = document.getElementById('langToggle');
  if (!toggle) return;

  let language = 'en';
  try {
    language = localStorage.getItem('siteLang') === 'id' ? 'id' : 'en';
  } catch {
    language = 'en';
  }

  updateLanguage(language);
  toggle.addEventListener('click', () => {
    language = language === 'en' ? 'id' : 'en';
    try {
      localStorage.setItem('siteLang', language);
    } catch {
      // Keep the selected language for the current page even when storage is unavailable.
    }
    updateLanguage(language);
  });
});
